using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Expose.Generator;


internal static class GeneratedSource
{
    public static string Emit(IReadOnlyList<Endpoint> endpoints)
    {
        var tab = " ".Repeat(4);
        var src = new StringBuilder();
        src.AppendLine("// <auto-generated />");
        src.AppendLine("#nullable enable");
        src.AppendLine("using Microsoft.AspNetCore.Builder;");
        src.AppendLine("using Microsoft.AspNetCore.Http;");
        src.AppendLine("using Microsoft.AspNetCore.Routing;");
        src.AppendLine("using ProtoBuf.Grpc.Server;");
        src.AppendLine();
        src.AppendLine("namespace Expose.Generated;");
        src.AppendLine();

        var records = SharedRecords(endpoints);
        foreach (var record in records)
            Messages.Append(src, record.Key, record.Value);
        if (records.Count > 0)
            src.AppendLine();

        src.AppendLine("public static class GeneratedEndpoints");
        src.AppendLine("{");
        HttpEmitter.Append(src, endpoints);
        src.AppendLine();
        src.AppendLine($"{tab}public static void MapGeneratedGrpc(this IEndpointRouteBuilder app) => app.MapGrpcService<GeneratedGrpcServices>();");
        src.AppendLine($"{tab}public static void MapGeneratedGraphQl(this IEndpointRouteBuilder app) => app.MapGraphQL();");
        src.AppendLine();
        src.AppendLine(
            $"{tab}public static void AddGeneratedGrpc(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services) => services.AddCodeFirstGrpc();");
        src.AppendLine();
        src.AppendLine($"{tab}public static void AddGeneratedGraphQl(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        src.AppendLine($"{tab}{{");
        src.AppendLine($"{tab.Repeat(2)}var server = services.AddGraphQLServer().AddQueryType<GeneratedQueries>();");
        if (endpoints.Any(endpoint => endpoint.GraphQl == GraphQlOperation.Mutation))
            src.AppendLine($"{tab.Repeat(2)}server.AddMutationType<GeneratedMutations>();");
        src.AppendLine($"{tab}}}");
        src.AppendLine("}");
        src.AppendLine();
        GrpcEmitter.Append(src, endpoints);
        GraphQlEmitter.Append(src, endpoints);
        return src.ToString();
    }

    private static Dictionary<string, List<Member>> SharedRecords(IReadOnlyList<Endpoint> endpoints)
    {
        var records = new Dictionary<string, List<Member>>();
        foreach (var endpoint in endpoints) {
            if (endpoint.ResponseRecord is not null && endpoint.ResponseFields is not null)
                records[endpoint.ResponseRecord] = endpoint.ResponseFields;
            foreach (var parameter in endpoint.Parameters) {
                if (parameter.Kind == ParameterKind.Body && parameter.Fields is not null)
                    records[parameter.Type] = parameter.Fields;
            }
        }

        return records;
    }
}
